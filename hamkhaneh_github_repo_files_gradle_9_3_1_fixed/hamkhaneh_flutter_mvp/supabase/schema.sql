-- PocketBase schema reference for خونمون; this file is documentation, not SQL.
-- Collections and fields must be created in the PocketBase Admin UI or via migrations.
--
-- Auth collection: users
--   name: text
--   avatar: file (optional)
--
-- Base collections:
-- houses
--   name: text (required)
--   invite_code: text
--   owner: relation(users), single, required
--   members: relation(users), multiple
--
-- tasks
--   house: relation(houses), single, required
--   title: text (required)
--   due_date: date
--   is_completed: bool
--   is_weekend: bool
--   assigned_to: relation(users), single; configure optional if tasks may be unassigned
--
-- shopping_items
--   house: relation(houses), single, required
--   name: text (required)
--   quantity: text
--   category: text
--   is_bought: bool
--   month_key: text (YYYY-MM)
--
-- App collection constants are users, houses, tasks, shopping_items. House membership
-- belongs in houses.members; do not create household_members or invites collections.
--
-- Security note: broad authenticated API rules may be useful for initial connection
-- testing, but they expose house/member data and are not production-safe. Tighten
-- list/view/create/update/delete rules to the authenticated owner and house members.
-- In particular, do not allow arbitrary clients to edit houses.members or invite_code.
-- For secure invite redemption, validate the code and add the user server-side (hook or
-- custom endpoint) atomically. Do not treat a client-side invite_code query as secure.
-- Rules are configured in PocketBase; no fabricated API rule syntax is provided here.
